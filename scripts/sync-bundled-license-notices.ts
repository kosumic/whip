import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { LicenseNotice } from './license-notice.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assetDirectory = resolve(root, 'assets/licenses/generated');
const registryPath = resolve(root, 'src/licenses/generated.ts');
const write = process.argv.includes('--write');
const inputPaths = [
  resolve(root, 'build/npm-direct-license-notices.json'),
  resolve(root, 'build/cargo-direct-license-notices.json'),
];

const notices = (await Promise.all(
  inputPaths.map(async path => JSON.parse(await readFile(path, 'utf8')) as LicenseNotice[]),
)).flat();
const categoryOrder = { npm: 0, cargo: 1 };
const assets = new Map<string, string>();
const registryNotices = notices
  .toSorted((left, right) => (
    categoryOrder[left.category] - categoryOrder[right.category] ||
    left.name.localeCompare(right.name) ||
    left.version.localeCompare(right.version)
  ))
  .map(notice => {
    const hash = createHash('sha256').update(notice.licenseText).digest('hex').slice(0, 16);
    const assetName = `${hash}.txt`;
    assets.set(assetName, notice.licenseText);
    const ecosystem = notice.category === 'npm' ? 'npm' : 'Rust';
    const usedBy = notice.usedBy?.length ? ` · used by ${notice.usedBy.join(' and ')}` : '';
    return {
      attribution: `Direct ${ecosystem} dependency · version ${notice.version}${usedBy}`,
      category: notice.category,
      id: `${notice.category}-${notice.name}-${notice.version}`
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, ''),
      licenseAsset: assetName,
      licenseName: notice.licenseName,
      projectName: notice.name,
      sourceUrl: notice.sourceUrl || (
        notice.category === 'npm'
          ? `https://www.npmjs.com/package/${notice.name}`
          : `https://crates.io/crates/${notice.name}`
      ),
    };
  });

const registry = renderRegistry(registryNotices);
if (write) {
  await mkdir(assetDirectory, { recursive: true });
  const expectedAssets = new Set(assets.keys());
  for (const existing of await readdir(assetDirectory)) {
    if (!expectedAssets.has(existing)) await unlink(resolve(assetDirectory, existing));
  }
  await Promise.all(
    [...assets].map(([name, text]) => writeFile(resolve(assetDirectory, name), text)),
  );
  await writeFile(registryPath, registry);
  console.log(
    `Wrote ${relativePath(registryPath)} with ${registryNotices.length} direct dependencies ` +
      `and ${assets.size} deduplicated license texts.`,
  );
} else {
  await assertCurrent(registryPath, registry);
  const existingAssets = (await readdir(assetDirectory)).sort();
  const expectedAssets = [...assets.keys()].sort();
  if (JSON.stringify(existingAssets) !== JSON.stringify(expectedAssets)) {
    throw new Error(
      `${relativePath(assetDirectory)} is stale; run npm run generate:license-notices`,
    );
  }
  await Promise.all(
    [...assets].map(([name, text]) => assertCurrent(resolve(assetDirectory, name), text)),
  );
  console.log(
    `Checked ${registryNotices.length} bundled direct dependencies and ` +
      `${assets.size} deduplicated license texts.`,
  );
}

function renderRegistry(entries: typeof registryNotices) {
  const renderedEntries = entries.map(entry => `  {
    id: ${quote(entry.id)},
    category: ${quote(entry.category)},
    projectName: ${quote(entry.projectName)},
    sourceUrl: ${quote(entry.sourceUrl)},
    attribution: ${quote(entry.attribution)},
    licenseName: ${quote(entry.licenseName)},
    licenseAsset: require(${quote(`../../assets/licenses/generated/${entry.licenseAsset}`)}),
  },`).join('\n');
  return `// Generated by npm run generate:license-notices. Do not edit manually.\n` +
    `export const GENERATED_OPEN_SOURCE_LICENSES = [\n${renderedEntries}\n] as const;\n`;
}

async function assertCurrent(path: string, expected: string) {
  let actual;
  try {
    actual = await readFile(path, 'utf8');
  } catch {
    throw new Error(`${relativePath(path)} is missing; run npm run generate:license-notices`);
  }
  if (actual !== expected) {
    throw new Error(`${relativePath(path)} is stale; run npm run generate:license-notices`);
  }
}

function quote(value: string) {
  return JSON.stringify(value);
}

function relativePath(path: string) {
  return path.slice(root.length + 1);
}
